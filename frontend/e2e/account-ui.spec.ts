import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

const credentials = JSON.parse(readFileSync('../artifacts/account-ui.json', 'utf8'))
const footerText = '仅用于数据筛选与投资研究，不构成投资建议、确定性预测或收益承诺。'

test('branded authentication, avatar navigation and account settings without AI calls', async ({ page, browser }) => {
  let aiCalls = 0
  const errors: string[] = []
  page.on('request', request => { if (request.url().endsWith('/api/interpret')) aiCalls++ })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('button', { name: '登录工作台', exact: true })).toBeVisible()
  for (const [width, height] of [[1440,900],[1280,800],[768,1024],[390,844]]) {
    await page.setViewportSize({ width, height })
    for (const mode of ['login', 'register']) {
      await page.getByRole('button', { name: mode === 'login' ? '账号登录' : '使用邀请码注册', exact: true }).click()
      await expect(page.locator('.site-footer').getByText(footerText, { exact: true })).toBeVisible()
      await expect(page.locator('.auth-header').getByText('内测版', { exact: true })).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
      await page.screenshot({ path: `../artifacts/auth-${mode}-${width}.png`, fullPage: true })
    }
  }
  await page.getByLabel('用户名', { exact: true }).fill(credentials.username)
  await page.getByLabel('密码', { exact: true }).fill(credentials.password)
  await page.getByLabel('邀请码', { exact: true }).fill(credentials.invite)
  await page.getByRole('button', { name: '创建账号', exact: true }).click()
  await expect(page.getByText('沪深300 · 已加载 300 只')).toBeVisible()
  await expect(page.locator('.account-bar')).toHaveCount(0)
  const trigger = page.getByLabel('打开账号菜单', { exact: true })
  for (const [width, height] of [[1440,900],[1280,800],[768,1024],[390,844]]) {
    await page.setViewportSize({ width, height })
    await trigger.click()
    await expect(page.getByRole('navigation', { name: '账号菜单' })).toBeVisible()
    const popup = await page.locator('.account-dropdown').boundingBox()
    expect(popup!.x).toBeGreaterThanOrEqual(0)
    expect(popup!.x + popup!.width).toBeLessThanOrEqual(width)
    const avatarBox = await trigger.boundingBox()
    const headerBox = await page.locator('.header-inner').boundingBox()
    expect(headerBox!.x + headerBox!.width - avatarBox!.x - avatarBox!.width).toBeLessThan(65)
    await page.screenshot({ path: `../artifacts/avatar-menu-${width}.png`, fullPage: true })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('navigation', { name: '账号菜单' })).not.toBeVisible()
    await expect(trigger).toBeFocused()
  }
  await trigger.press('Enter')
  await page.getByRole('button', { name: '我的策略', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '我的策略', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关闭我的策略' }).click()
  await trigger.click()
  await page.locator('.identity-name').click()
  await expect(page.getByRole('navigation', { name: '账号菜单' })).not.toBeVisible()
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
  await expect(page.locator('.site-header')).toBeInViewport()
  await trigger.click()
  await page.getByRole('button', { name: '我的账号设置', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '我的账号设置' })).toBeVisible()
  await expect(page.locator('.account-info')).toContainText(credentials.username)
  await expect(page.locator('.account-info')).toContainText('0 / 5 次')
  await page.screenshot({ path: '../artifacts/account-settings-390.png', fullPage: true })
  const another = await browser.newContext()
  expect((await another.request.post('http://127.0.0.1:5174/api/account/login', { data: { username: credentials.username, password: credentials.password } })).ok()).toBeTruthy()
  const newPassword = credentials.password + '-new'
  await page.getByLabel('当前密码', { exact: true }).fill('wrong-password')
  await page.getByLabel('新密码', { exact: true }).fill(newPassword)
  await page.getByLabel('确认新密码', { exact: true }).fill(newPassword)
  await page.getByRole('button', { name: '更新密码' }).click()
  await expect(page.getByRole('alert')).toHaveText('当前密码不正确')
  await page.getByLabel('当前密码', { exact: true }).fill(credentials.password)
  await page.getByRole('button', { name: '更新密码' }).click()
  await expect(page.getByText('密码已更新，其他登录会话已退出。')).toBeVisible()
  expect((await another.request.get('http://127.0.0.1:5174/api/account/me')).status()).toBe(401)
  await another.close()
  await page.getByRole('button', { name: '关闭账号设置' }).click()
  await trigger.click()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '登录工作台', exact: true })).toBeVisible()
  await expect(page.locator('.site-footer')).toContainText(footerText)
  await page.getByLabel('用户名', { exact: true }).fill(credentials.username)
  await page.getByLabel('密码', { exact: true }).fill(newPassword)
  await page.getByRole('button', { name: '登录工作台', exact: true }).click()
  await expect(trigger).toBeVisible()
  expect(aiCalls).toBe(0)
  expect(errors).toEqual([])
})
