import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { makeSnapshot, metricKeys } from '../src/strategies'

const credentials = JSON.parse(readFileSync('../artifacts/multi-industry.json', 'utf8'))
test('compact editor, multiple industries, saved snapshot and readable real-data provenance', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const errors: string[] = []
  let aiCalls = 0
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', request => { if (request.url().endsWith('/api/interpret')) aiCalls++ })
  await page.goto('/')
  await page.getByRole('button', { name: '使用邀请码注册' }).click()
  await page.getByLabel('用户名', { exact: true }).fill(credentials.username)
  await page.getByLabel('密码', { exact: true }).fill(credentials.password)
  await page.getByLabel('邀请码', { exact: true }).fill(credentials.invite)
  await page.getByRole('button', { name: '创建账号', exact: true }).click()
  await expect(page.getByLabel('打开账号菜单')).toBeVisible()
  await page.setViewportSize({width:1440,height:900})
  const centers = await page.locator('.hero h1, .hero-subtitle, .composer-card').evaluateAll(nodes => nodes.map(node => { const box=node.getBoundingClientRect(); return box.x+box.width/2 }))
  expect(Math.max(...centers)-Math.min(...centers)).toBeLessThan(2)
  await page.screenshot({path:'../artifacts/centered-workspace-1440.png',fullPage:true})
  const draft = Object.fromEntries(metricKeys.map(key => [key, ({pe_max:20,profit_min:5,vol_max:4,pb_max:3,roe_min:5,revenue_min:0})[key].toString()])) as Record<typeof metricKeys[number],string>
  const now = new Date().toISOString()
  const saved = await page.request.put('/api/account/strategies', {data: { revision:0, items:[{schemaVersion:2,id:'multi-acceptance',name:'条件工作台验收',query:'银行股，多维度条件观察',provider:'deepseek',createdAt:now,updatedAt:now,snapshot:makeSnapshot(draft,metricKeys,'881155.TI')}] }})
  expect(saved.ok()).toBeTruthy()
  await page.getByLabel('打开账号菜单').click()
  await page.getByRole('button', {name:'我的策略',exact:true}).click()
  await page.getByRole('button', {name:'载入并编辑'}).click()
  await page.getByLabel('选择行业', {exact:true}).click()
  await page.getByLabel('搜索行业', {exact:true}).fill('白酒')
  await page.getByRole('checkbox', {name:'白酒'}).check()
  await page.getByLabel('选择行业', {exact:true}).click()
  await page.getByRole('button', {name:'保存更改',exact:true}).click()
  await page.getByRole('button', {name:'确认保存',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await page.getByLabel('打开账号菜单').click()
  await page.getByRole('button', {name:'我的策略',exact:true}).click()
  await page.getByRole('button', {name:'载入并编辑'}).click()
  await expect(page.locator('.industry-picker summary')).toContainText('银行')
  await expect(page.locator('.industry-picker summary')).toContainText('白酒')
  for (const [width,height] of [[1440,900],[1280,800],[768,1024],[390,844]]) {
    await page.setViewportSize({width,height})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    const save = await page.getByRole('button',{name:'保存更改',exact:true}).boundingBox()
    const run = await page.getByRole('button',{name:'确认并执行筛选',exact:true}).boundingBox()
    expect(save!.x).toBeLessThan(run!.x)
    expect(save!.width).toBeLessThan(run!.width)
    expect(Math.abs(save!.y-run!.y)).toBeLessThan(2)
    if(width>=1280) {
      const heights = await page.locator('.condition-card').evaluateAll(nodes=>nodes.map(node=>node.getBoundingClientRect().height))
      expect(Math.max(...heights)).toBeLessThan(135)
    }
    await page.screenshot({path:`../artifacts/compact-editor-${width}.png`,fullPage:true})
  }
  await page.getByRole('button', {name:'确认并执行筛选',exact:true}).click()
  await expect(page.getByRole('heading',{name:'每只股票，都有筛选依据'})).toBeVisible()
  await expect(page.locator('.applied-rules')).toContainText('银行')
  await expect(page.locator('.applied-rules')).toContainText('白酒')
  await page.getByRole('button',{name:'保存策略参数',exact:true}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button',{name:'取消',exact:true}).click()
  await page.locator('.stock-name-button').first().click()
  await expect(page.getByRole('heading',{name:'数据来源与计算依据'})).toBeVisible()
  await expect(page.locator('.data-provenance-panel')).toContainText('PE TTM 使用过去12个月盈利口径')
  await expect(page.locator('.data-provenance-panel')).toContainText('采用报告期')
  await expect(page.locator('.trace-details')).not.toHaveAttribute('open','')
  await page.getByText('查看计算用的21个收盘价',{exact:true}).click()
  await expect(page.locator('.calculation-inputs tbody tr')).toHaveCount(21)
  await page.getByRole('heading',{name:'数据来源与计算依据'}).scrollIntoViewIfNeeded()
  await page.screenshot({path:'../artifacts/readable-provenance-390.png'})
  await page.getByRole('button',{name:'关闭股票详情'}).click()
  await page.setViewportSize({width:1440,height:900})
  await page.screenshot({path:'../artifacts/result-actions-1440.png',fullPage:true})
  expect(aiCalls).toBe(0)
  expect(errors).toEqual([])
})
