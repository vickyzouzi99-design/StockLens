import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

const credentials = JSON.parse(readFileSync('../artifacts/e2e-account.json', 'utf8'))
test('real account, strategy lifecycle, evidence and four viewport layouts', async ({ page }) => {
  test.setTimeout(240000)
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button', { name: '使用邀请码注册' }).click()
  await page.getByLabel('用户名').fill(credentials.username)
  await page.getByLabel('密码').fill(credentials.password)
  await page.getByLabel('邀请码', { exact: true }).fill(credentials.invite)
  await page.getByRole('button', { name: '创建账号' }).click()
  await expect(page.getByText('沪深300 · 已加载 300 只')).toBeVisible()
  for (const [width, height] of [[1440,900], [1280,800], [768,1024], [390,844]]) {
    await page.setViewportSize({ width, height })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await expect(page.getByRole('button', { name: '解析选股需求', exact: true })).toBeInViewport()
    await page.screenshot({ path: `../artifacts/step1-${width}.png`, fullPage: true })
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByLabel('描述你的选股需求').fill('银行股，市净率不超过2倍，净资产收益率至少8%')
  await page.getByLabel('AI 服务', { exact: true }).selectOption('deepseek')
  await page.getByRole('button', { name: '解析选股需求', exact: true }).click()
  await expect(page.getByRole('heading', { name: '确认你的选股条件', exact: true })).toBeVisible({ timeout: 65000 })
  await page.locator('#metric-pb_max').fill('2')
  await page.getByRole('button', { name: '＋ 关注估值水平', exact: true }).click()
  await page.locator('#metric-pe_max').fill('20')
  await page.getByRole('button', { name: '移除估值水平筛选条件' }).click()
  await page.getByRole('button', { name: '保存策略', exact: true }).click()
  await page.getByLabel('策略名称').fill('验收策略')
  await page.getByRole('button', { name: '确认保存', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: '我的策略', exact: true }).click()
  await page.getByRole('button', { name: '载入并编辑', exact: true }).click()
  let interpretCalls = 0
  page.on('request', request => { if (request.url().endsWith('/api/interpret')) interpretCalls++ })
  await page.getByRole('button', { name: '＋ 关注估值水平', exact: true }).click()
  await expect(page.locator('#metric-pe_max')).toHaveValue('20')
  await page.locator('#metric-pe_max').fill('30')
  await expect(page.getByText('有未保存的修改', { exact: false })).toBeVisible()
  for (const [width, height] of [[1440,900],[1280,800],[768,1024],[390,844]]) {
    await page.setViewportSize({ width, height })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.screenshot({ path: `../artifacts/step2-${width}.png`, fullPage: true })
  }
  await page.getByRole('button', { name: '确认并执行筛选', exact: true }).click()
  await expect(page.getByRole('heading', { name: '每只股票，都有筛选依据' })).toBeVisible()
  await page.locator('.stock-name-button').first().click()
  await expect(page.getByRole('heading', { name: '逐项条件核验' })).toBeVisible()
  await page.getByRole('button', { name: '关闭股票详情' }).click()
  for (const [width,height] of [[1440,900],[1280,800],[768,1024],[390,844]]) {
    await page.setViewportSize({ width,height })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.screenshot({ path: `../artifacts/step3-${width}.png`, fullPage: true })
  }
  await page.getByRole('button', { name: '保存更改', exact: true }).click()
  await page.getByRole('button', { name: '确认保存', exact: true }).click()
  await page.getByRole('button', { name: '我的策略', exact: true }).click()
  await page.getByRole('button', { name: '复制', exact: true }).click()
  await page.getByLabel('策略名称').fill('副本')
  await page.getByRole('button', { name: '确认保存', exact: true }).click()
  await expect(page.locator('.strategy-drawer article')).toHaveCount(2)
  page.on('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除', exact: true }).last().click()
  await expect(page.locator('.strategy-drawer article')).toHaveCount(1)
  expect(interpretCalls).toBe(0)
  expect(errors).toEqual([])
})
